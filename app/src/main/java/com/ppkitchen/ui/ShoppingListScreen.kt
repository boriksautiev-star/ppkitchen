package com.ppkitchen.ui

import android.content.Intent
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.Refresh
import androidx.compose.material.icons.filled.Share
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.window.Dialog
import androidx.compose.ui.window.DialogProperties
import com.ppkitchen.data.ShoppingItem
import com.ppkitchen.data.ShoppingListGenerator
import kotlinx.coroutines.launch

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ShoppingListScreen(
    startDate: String,
    onDismiss: () -> Unit
) {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()

    var daysInput by remember { mutableStateOf("7") }
    var isGenerating by remember { mutableStateOf(false) }
    var generatedData by remember { mutableStateOf<Map<String, List<ShoppingItem>>>(emptyMap()) }
    var hasGenerated by remember { mutableStateOf(false) }

    fun generateList() {
        val days = daysInput.toIntOrNull() ?: return
        if (days <= 0) return

        isGenerating = true
        scope.launch {
            generatedData = ShoppingListGenerator.generate(ctx, startDate, days)
            isGenerating = false
            hasGenerated = true
        }
    }

    LaunchedEffect(Unit) {
        generateList()
    }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
            Column(Modifier.fillMaxSize()) {
                CompactTopBar(
                    title = "Список закупок",
                    onBack = onDismiss,
                    actions = {
                        if (hasGenerated && generatedData.isNotEmpty()) {
                            IconButton(
                                onClick = {
                                    val days = daysInput.toIntOrNull() ?: 7
                                    val text = ShoppingListGenerator.formatToString(generatedData, startDate, days)
                                    val sendIntent = Intent().apply {
                                        action = Intent.ACTION_SEND
                                        putExtra(Intent.EXTRA_TEXT, text)
                                        type = "text/plain"
                                    }
                                    ctx.startActivity(Intent.createChooser(sendIntent, "Отправить список закупок"))
                                }
                            ) {
                                Icon(Icons.Default.Share, "Поделиться")
                            }
                        }
                    }
                )

                Card(
                    modifier = Modifier.fillMaxWidth().padding(16.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)
                ) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        Text("Период закупки", style = MaterialTheme.typography.titleSmall, fontWeight = FontWeight.Bold)
                        Text("Начало: $startDate", style = MaterialTheme.typography.bodyMedium)

                        Row(
                            Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.spacedBy(8.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            OutlinedTextField(
                                value = daysInput,
                                onValueChange = { daysInput = it.filter { ch -> ch.isDigit() } },
                                label = { Text("Дней") },
                                modifier = Modifier.weight(1f),
                                singleLine = true
                            )
                            Button(
                                onClick = { generateList() },
                                enabled = !isGenerating && daysInput.isNotBlank()
                            ) {
                                Icon(Icons.Default.Refresh, null)
                                Spacer(Modifier.width(4.dp))
                                Text("Обновить")
                            }
                        }
                    }
                }

                if (isGenerating) {
                    Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                        CircularProgressIndicator()
                    }
                } else if (generatedData.isEmpty()) {
                    Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                        Text("На этот период нет заказов с меню.", style = MaterialTheme.typography.bodyLarge)
                    }
                } else {
                    LazyColumn(
                        modifier = Modifier.fillMaxSize(),
                        contentPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp),
                        verticalArrangement = Arrangement.spacedBy(16.dp)
                    ) {
                        val sortedCategories = generatedData.keys.sorted()
                        sortedCategories.forEach { category ->
                            item {
                                Text(category, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                                HorizontalDivider(Modifier.padding(top = 4.dp, bottom = 4.dp))
                            }
                            val items = generatedData[category] ?: emptyList()
                            items(items, key = { it.ingredient.id }) { item ->
                                Row(
                                    Modifier.fillMaxWidth().padding(vertical = 4.dp),
                                    horizontalArrangement = Arrangement.SpaceBetween
                                ) {
                                    Text(item.ingredient.name, style = MaterialTheme.typography.bodyMedium)

                                    // ИСПОЛЬЗУЕМ ПРАВИЛЬНУЮ ФУНКЦИЮ ФОРМАТИРОВАНИЯ
                                    val amountStr = ShoppingListGenerator.formatAmount(item.totalAmount, item.ingredient.unit)

                                    Text(amountStr, style = MaterialTheme.typography.bodyMedium, fontWeight = FontWeight.Bold)
                                }
                            }
                        }
                        item { Spacer(Modifier.height(32.dp)) }
                    }
                }
            }
        }
    }
}